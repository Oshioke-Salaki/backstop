// Writes the escrow ABI into @backstop/core so TypeScript call sites are type-checked against the contract.
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import path from "node:path";

const root = path.dirname(fileURLToPath(import.meta.url));
const read = (p) => JSON.parse(readFileSync(path.join(root, "..", "out", p), "utf8")).abi;
const escrow = read("BackstopEscrow.sol/BackstopEscrow.json");
const usdc = read("MockUSDC.sol/MockUSDC.json").filter((f) =>
  ["balanceOf", "authorizationState", "transferWithAuthorization", "decimals", "name", "version"].includes(f.name),
);

const out = `// Generated by contracts/scripts/export-abi.mjs. Do not edit.
export const escrowAbi = ${JSON.stringify(escrow, null, 2)} as const;

export const erc3009Abi = ${JSON.stringify(usdc, null, 2)} as const;
`;
writeFileSync(path.join(root, "..", "..", "packages", "core", "src", "abi.ts"), out);
console.log(`wrote ${escrow.length} escrow ABI entries`);
